// Lists which read-aloud clips exist, so the game knows before a child taps whether to play a
// recording or speak with the device's own voice. Phones only allow speech that starts right at
// the tap, so the game cannot afford to "try the clip, then fall back" after a failed download.
// Runs automatically before `dev` and `build`; the result is committed too.
import { readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../public/career-day/audio/", import.meta.url);
const ids = readdirSync(dir)
  .filter((f) => f.endsWith(".mp3"))
  .map((f) => f.slice(0, -4))
  .sort();

const out = new URL("../src/lib/clip-manifest.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/make-clip-manifest.mjs. Do not edit by hand.
const recorded = new Set<string>([
${ids.map((id) => `  "${id}",`).join("\n")}
]);

export const hasRecordedClip = (id: string) => recorded.has(id);
`
);
console.log(`clip manifest: ${ids.length} clips`);
